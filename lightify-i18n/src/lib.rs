//! Lightify's translations, Rust side.
//!
//! The app's `.slint` text is translated by Slint (`@tr`, catalogs bundled at build time).
//! The strings Rust builds — status messages, menus, prompts — go through [`tr!`] here,
//! which reads **the same catalogs**: one `.po` file per language holds both, so a
//! translator sees each English string once. The English text is the key; anything
//! without a translation stays English.
//!
//! Placeholders follow Slint's `@tr` rules so both halves read alike: `{}` takes the next
//! argument, `{0}` `{1}` … a numbered one, `{n}` the count in [`trn!`], `{{` `}}` are
//! literal braces.

pub mod build;
pub mod check;
mod po;

use std::sync::RwLock;

pub use po::{Catalog, Entry};

/// A language bundled into the program: its code (the catalog's folder name, `de`,
/// `pt-BR`) and its catalog text. Generated by the app's build script.
pub struct Lang {
    pub code: &'static str,
    pub po: &'static str,
}

struct State {
    code: String,
    catalog: Option<Catalog>,
}

static STATE: RwLock<State> = RwLock::new(State { code: String::new(), catalog: None });

/// The source language: the text as written in the code.
pub const ENGLISH: &str = "en";

/// Makes `code` the active language for Rust-side strings (`""`/`"en"` = English).
/// Returns the code now active — English when `code` isn't among `langs` or its catalog
/// can't be read (a broken catalog must never take the app down).
pub fn select(langs: &[Lang], code: &str) -> String {
    let found = langs.iter().find(|l| l.code.eq_ignore_ascii_case(code));
    let (code, catalog) = match found.map(|l| (l.code, Catalog::parse(l.po))) {
        Some((c, Ok(cat))) => (c.to_string(), Some(cat)),
        _ => (ENGLISH.to_string(), None),
    };
    let mut st = STATE.write().unwrap_or_else(|p| p.into_inner());
    st.code = code.clone();
    st.catalog = catalog;
    code
}

/// The active language's code (`en` until something else is selected).
pub fn current() -> String {
    let st = STATE.read().unwrap_or_else(|p| p.into_inner());
    if st.code.is_empty() {
        ENGLISH.to_string()
    } else {
        st.code.clone()
    }
}

/// Which language a setting means. `setting` is what the user saved: `auto` (or empty)
/// follows `system` (Windows' display languages, most preferred first); anything else is
/// a language code. A code matches exactly first, then by its base language (`de-AT` →
/// `de`, `pt` → `pt-BR`); no match is English.
pub fn resolve(setting: &str, available: &[&str], system: &[String]) -> String {
    let setting = setting.trim();
    let wanted: Vec<&str> = if setting.is_empty() || setting.eq_ignore_ascii_case("auto") {
        system.iter().map(String::as_str).collect()
    } else {
        vec![setting]
    };
    let base = |s: &str| s.split(['-', '_']).next().unwrap_or(s).to_ascii_lowercase();
    for w in &wanted {
        if base(w) == ENGLISH {
            return ENGLISH.to_string();
        }
        if let Some(a) = available.iter().find(|a| a.eq_ignore_ascii_case(w)) {
            return a.to_string();
        }
        if let Some(a) = available.iter().find(|a| base(a) == base(w)) {
            return a.to_string();
        }
    }
    ENGLISH.to_string()
}

/// Windows' display languages, most preferred first (`de-DE`, `en-US`, …). Empty when
/// Windows won't say (or off Windows).
pub fn system_languages() -> Vec<String> {
    #[cfg(windows)]
    {
        #[link(name = "kernel32")]
        extern "system" {
            fn GetUserPreferredUILanguages(flags: u32, num: *mut u32, buf: *mut u16, len: *mut u32) -> i32;
        }
        const MUI_LANGUAGE_NAME: u32 = 0x8;
        let (mut num, mut len) = (0u32, 0u32);
        // SAFETY: the documented two-call pattern — size first, then a buffer that big.
        unsafe {
            if GetUserPreferredUILanguages(MUI_LANGUAGE_NAME, &mut num, std::ptr::null_mut(), &mut len) == 0 || len == 0 {
                return Vec::new();
            }
            let mut buf = vec![0u16; len as usize];
            if GetUserPreferredUILanguages(MUI_LANGUAGE_NAME, &mut num, buf.as_mut_ptr(), &mut len) == 0 {
                return Vec::new();
            }
            // A double-NUL-terminated list of NUL-separated names.
            buf.split(|&c| c == 0).filter(|s| !s.is_empty()).map(String::from_utf16_lossy).collect()
        }
    }
    #[cfg(not(windows))]
    Vec::new()
}

/// Languages whose catalog is a machine draft no native speaker has read yet: the
/// language lists show them as "(preview)". Take a code out once someone has.
pub const PREVIEW: &[&str] = &["de", "es", "fr", "pt-BR", "it", "nl", "pl", "ru", "ja", "zh-CN", "ko"];

/// Is `code` still a [`PREVIEW`] language?
pub fn is_preview(code: &str) -> bool {
    PREVIEW.iter().any(|p| p.eq_ignore_ascii_case(code))
}

/// A language's name in that language, for the language list.
pub fn native_name(code: &str) -> String {
    let name = match code.to_ascii_lowercase().as_str() {
        "en" => "English",
        "de" => "Deutsch",
        "es" => "Español",
        "fr" => "Français",
        "it" => "Italiano",
        "nl" => "Nederlands",
        "pl" => "Polski",
        "pt" => "Português",
        "pt-br" => "Português (Brasil)",
        "pt-pt" => "Português (Portugal)",
        "sv" => "Svenska",
        "da" => "Dansk",
        "nb" | "no" => "Norsk",
        "fi" => "Suomi",
        "cs" => "Čeština",
        "tr" => "Türkçe",
        "ro" => "Română",
        "hu" => "Magyar",
        "vi" => "Tiếng Việt",
        "ru" => "Русский",
        "uk" => "Українська",
        "el" => "Ελληνικά",
        "ja" => "日本語",
        "zh-cn" | "zh-hans" => "简体中文",
        "zh-tw" | "zh-hant" => "繁體中文",
        "ko" => "한국어",
        _ => return code.to_string(),
    };
    name.to_string()
}

/// `msgid` in the active language, as written when there is no translation.
pub fn translate(msgid: &str) -> String {
    let st = STATE.read().unwrap_or_else(|p| p.into_inner());
    st.catalog.as_ref().and_then(|c| c.get("", msgid)).unwrap_or(msgid).to_string()
}

/// The plural form for `n`; English picks `singular` for 1 and `plural` otherwise.
pub fn translate_plural(singular: &str, plural: &str, n: u64) -> String {
    let st = STATE.read().unwrap_or_else(|p| p.into_inner());
    if let Some(s) = st.catalog.as_ref().and_then(|c| c.get_plural("", singular, n)) {
        return s.to_string();
    }
    if n == 1 { singular } else { plural }.to_string()
}

/// Fills `{}` (next argument), `{0}` … (numbered) and `{n}` (the count) in `template`;
/// `{{`/`}}` are literal braces. A placeholder with no matching argument is left as
/// written, so a slip in a translation shows instead of panicking.
pub fn fill(template: &str, args: &[String], n: Option<u64>) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut next = 0usize;
    let mut rest = template;
    while let Some(i) = rest.find(['{', '}']) {
        out.push_str(&rest[..i]);
        let tail = &rest[i..];
        if tail.starts_with("{{") || tail.starts_with("}}") {
            out.push(tail.as_bytes()[0] as char);
            rest = &tail[2..];
            continue;
        }
        if let (true, Some(end)) = (tail.starts_with('{'), tail.find('}')) {
            let key = &tail[1..end];
            let value = if key.is_empty() {
                next += 1;
                args.get(next - 1).cloned()
            } else if key == "n" {
                n.map(|n| n.to_string())
            } else {
                key.parse::<usize>().ok().and_then(|k| args.get(k).cloned())
            };
            match value {
                Some(v) => out.push_str(&v),
                None => out.push_str(&tail[..=end]),
            }
            rest = &tail[end + 1..];
        } else {
            out.push(tail.as_bytes()[0] as char);
            rest = &tail[1..];
        }
    }
    out.push_str(rest);
    out
}

/// `tr!("Settings")`, `tr!("Added {} to queue", n)`: the active language's text for an
/// English string literal, placeholders filled. Always a `String`.
#[macro_export]
macro_rules! tr {
    ($msgid:literal $(,)?) => {
        $crate::fill(&$crate::translate($msgid), &[], None)
    };
    ($msgid:literal, $($arg:expr),+ $(,)?) => {
        $crate::fill(&$crate::translate($msgid), &[$(($arg).to_string()),+], None)
    };
}

/// `trn!("{n} track", "{n} tracks", count)` (plus `{}` arguments after the count): the
/// plural form for `count` in the active language.
#[macro_export]
macro_rules! trn {
    ($one:literal, $many:literal, $n:expr $(, $arg:expr)* $(,)?) => {{
        let n = ($n) as u64;
        $crate::fill(&$crate::translate_plural($one, $many, n), &[$(($arg).to_string()),*], Some(n))
    }};
}

/// `tr_noop!("Downloader bridge")`: the English literal, unchanged, marked for the
/// template — for a string that is also matched as a key, so it is translated later,
/// where it's shown (`translate`).
#[macro_export]
macro_rules! tr_noop {
    ($msgid:literal) => {
        $msgid
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    static DE: &str = "msgid \"\"\nmsgstr \"Plural-Forms: nplurals=2; plural=(n != 1);\\n\"\n\n\
        msgid \"Settings\"\nmsgstr \"Einstellungen\"\n\n\
        msgid \"Added {} to queue\"\nmsgstr \"{} zur Warteschlange hinzugefügt\"\n\n\
        msgid \"{n} track\"\nmsgid_plural \"{n} tracks\"\nmsgstr[0] \"{n} Titel\"\nmsgstr[1] \"{n} Titel*\"\n";
    static LANGS: &[Lang] = &[Lang { code: "de", po: DE }, Lang { code: "pt-BR", po: "" }];

    // The active language is process-wide; keep the tests that switch it in one place.
    #[test]
    fn switching_and_lookups() {
        assert_eq!(select(LANGS, "en"), "en");
        assert_eq!(tr!("Settings"), "Settings");
        assert_eq!(tr!("Added {} to queue", 3), "Added 3 to queue");
        assert_eq!(trn!("{n} track", "{n} tracks", 1), "1 track");
        assert_eq!(trn!("{n} track", "{n} tracks", 4), "4 tracks");

        assert_eq!(select(LANGS, "de"), "de");
        assert_eq!(current(), "de");
        assert_eq!(tr!("Settings"), "Einstellungen");
        assert_eq!(tr!("Added {} to queue", 3), "3 zur Warteschlange hinzugefügt");
        assert_eq!(tr!("Not in the catalog"), "Not in the catalog");
        assert_eq!(trn!("{n} track", "{n} tracks", 1), "1 Titel");
        assert_eq!(trn!("{n} track", "{n} tracks", 2), "2 Titel*");

        // Unknown or unreadable: English, never a panic.
        assert_eq!(select(LANGS, "xx"), "en");
        assert_eq!(tr!("Settings"), "Settings");
        assert_eq!(select(&[Lang { code: "bad", po: "msgid unquoted" }], "bad"), "en");
    }

    #[test]
    fn resolving_a_setting() {
        let avail = ["de", "pt-BR", "fr"];
        let sys = |v: &[&str]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        assert_eq!(resolve("auto", &avail, &sys(&["de-AT", "en-US"])), "de");
        assert_eq!(resolve("", &avail, &sys(&["pt-PT"])), "pt-BR");
        assert_eq!(resolve("auto", &avail, &sys(&["en-GB", "de-DE"])), "en", "English preferred first");
        assert_eq!(resolve("auto", &avail, &sys(&["ja-JP", "fr-CA"])), "fr", "first one we have");
        assert_eq!(resolve("auto", &avail, &[]), "en");
        assert_eq!(resolve("fr", &avail, &sys(&["de-DE"])), "fr", "a chosen language beats Windows'");
        assert_eq!(resolve("it", &avail, &sys(&["de-DE"])), "en", "chosen but not bundled");
        assert_eq!(resolve("auto", &[], &sys(&["de-DE"])), "en", "nothing bundled");
    }

    #[test]
    fn placeholders() {
        let a = |v: &[&str]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        assert_eq!(fill("{} of {}", &a(&["1", "9"]), None), "1 of 9");
        assert_eq!(fill("{1} before {0}", &a(&["a", "b"]), None), "b before a");
        assert_eq!(fill("{n} tracks in {}", &a(&["Focus"]), Some(3)), "3 tracks in Focus");
        assert_eq!(fill("{{literal}} {}", &a(&["x"]), None), "{literal} x");
        assert_eq!(fill("missing {} {2}", &[], None), "missing {} {2}");
        assert_eq!(fill("odd } and { brace", &[], None), "odd } and { brace");
        assert_eq!(fill("Ünïcødé {}", &a(&["✓"]), None), "Ünïcødé ✓");
    }

    #[test]
    fn windows_reports_a_language() {
        let langs = system_languages();
        #[cfg(windows)]
        assert!(!langs.is_empty() && langs[0].contains('-'), "{langs:?}");
        let _ = langs;
    }
}
